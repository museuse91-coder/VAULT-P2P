export function generateCandleSeries(basePrice: number, count = 72, stepSeconds = 3600): Candle[] {
  const candles: Candle[] = [];
  const nowSec = Math.floor(Date.now() / 1000);
  let price = basePrice * 0.965;

  // Deterministic-feeling random walk ending near basePrice
  for (let i = count; i >= 1; i--) {
    const t = nowSec - i * stepSeconds;
    const progress = (count - i) / count;
    const target = basePrice * (0.965 + 0.035 * progress);
    const drift = (target - price) * 0.22;
    const volatility = basePrice * 0.0065;
    const delta = drift + (Math.sin(i * 1.73) * 0.4 + (Math.random() - 0.48)) * volatility;
    const open = price;
    const close = i === 1 ? basePrice : Math.max(basePrice * 0.5, open + delta);
    const wickUp = Math.random() * volatility * 0.85;
    const wickDown = Math.random() * volatility * 0.85;
    const high = Math.max(open, close) + wickUp;
    const low = Math.max(basePrice * 0.4, Math.min(open, close) - wickDown);
    const volume = (Math.abs(close - open) / basePrice) * 140000 + 250 + Math.random() * 650;
    candles.push({
      time: t,
      open,
      high,
      low,
      close,
      volume,
    });
    price = close;
  }
  return candles;
}
